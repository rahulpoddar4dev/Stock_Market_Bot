def _read_existing_rows() -> list[dict]:
    if not HISTORY_FILE.exists():
        return []

    with HISTORY_FILE.open() as csv_file:
        return list(csv.DictReader(csv_file))


def _append_to_file(path: Path, row: dict, base_fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = []

    if path.exists():
        with path.open() as csv_file:
            rows = list(csv.DictReader(csv_file))

    fieldnames = list(base_fieldnames)
    for existing_row in rows:
        for fieldname in existing_row.keys():
            if fieldname and fieldname not in fieldnames:
                fieldnames.append(fieldname)

    with path.open("w", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=fieldnames)
        writer.writeheader()
        for existing_row in rows:
            writer.writerow(existing_row)
        writer.writerow(row)


